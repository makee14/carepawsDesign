#!/usr/bin/env python3
"""CarePaws icon artwork pipeline — the lockstep between SVG sources and Dart.

Source of truth: tool/icon/app_icon.svg (hand-authored, CarePaws mark v5).
Colors live ONCE as CSS custom properties in its :root block, mirroring
lib/design/tokens.dart. Everything else is GENERATED by this script:

  tool/icon/app_icon_foreground.svg   adaptive-icon foreground (stamped)
  tool/icon/app_icon_nocircle.svg      silhouettes only, for light surfaces
  lib/design/icons.dart               badgeArtwork, launcherArtwork,
                                      launcherForegroundArtwork,
                                      badgeNoCircleArtwork, splashLayer*

Why stamping: flutter_svg cannot resolve var() (verified against 2.3.0
sources) and rsvg-convert renders var() fills as empty, so every generated
artifact gets the :root values inlined as literals. The script also enforces
palette discipline: any hex that is not a named variable fails the run.

Usage:
  tool/sync_icons_dart.py                  regenerate everything
  tool/sync_icons_dart.py --stamp OUT.svg   write stamped master to OUT.svg
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVGNS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVGNS)


def Q(tag: str) -> str:
    return f"{{{SVGNS}}}{tag}"


HERE = Path(__file__).resolve().parent
ICON_DIR = HERE / "icon"
DART_FILE = HERE.parent / "lib" / "design" / "icons.dart"
MASTER = ICON_DIR / "app_icon.svg"

GROUP_IDS = ("cp-circle", "cp-dog", "cp-cat", "cp-heart")


def parse_master():
    root = ET.parse(MASTER).getroot()
    style = root.find(f".//{Q('style')}")
    varmap = dict(re.findall(r"--([\w-]+)\s*:\s*(#[0-9A-Fa-f]{6})", style.text or ""))
    if not varmap:
        sys.exit("sync_icons_dart: no :root variables found in master SVG")
    badge = root.find(f'.//{Q("g")}[@id="cp-badge"]')
    if badge is None:
        sys.exit("sync_icons_dart: master is missing <g id=\"cp-badge\">")
    groups = {}
    for gid in GROUP_IDS:
        g = badge.find(f'{Q("g")}[@id="{gid}"]')
        if g is None:
            sys.exit(f"sync_icons_dart: master is missing <g id=\"{gid}\">")
        groups[gid] = g
    return root, badge, groups, varmap


def stamp(s: str, varmap: dict) -> str:
    def rep(m):
        name = m.group(1)
        if name not in varmap:
            sys.exit(f"sync_icons_dart: unresolved var(--{name})")
        return varmap[name]

    out = re.sub(r"var\(--([\w-]+)\)", rep, s)
    known = {v.upper() for v in varmap.values()} | {"#FFFFFF", "#000000"}
    for hx in set(re.findall(r"#[0-9A-Fa-f]{6}", out)):
        if hx.upper() not in known:
            sys.exit(f"sync_icons_dart: {hx} is not a named color variable")
    if "var(" in out:
        sys.exit("sync_icons_dart: unresolved var() remains after stamping")
    return out


def one_line(s: str) -> str:
    """Collapse an SVG document to one line for a Dart string literal."""
    return re.sub(r"\s+", " ", s).strip()


def doc(inner: str, varmap: dict, comment: str) -> str:
    named = " ".join(f"{k}={v}" for k, v in varmap.items())
    head = (
        f"<!-- Generated by tool/sync_icons_dart.py — do not hand-edit. "
        f"Named colors: {named}. -->"
    )
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
        f'viewBox="0 0 1024 1024">{head}{inner}</svg>'
    )
    return one_line(stamp(svg, varmap))


def children_str(el, tag=None) -> str:
    return "".join(
        ET.tostring(c, encoding="unicode") for c in el if tag is None or c.tag == Q(tag)
    )


def build_foreground(badge) -> str:
    inner = (
        '<g transform="translate(512 512) scale(0.6) translate(-512 -512)">'
        + ET.tostring(badge, encoding="unicode")
        + "</g>"
    )
    return inner


def build_nocircle(groups) -> str:
    # Pets + heart in brand orange (the heart merges with the pets, reading
    # as one solid mark); eyes knocked out via mask so any light surface
    # shows through.
    cut_shapes = ""
    for gid in ("cp-dog", "cp-cat"):
        for e in groups[gid].findall(Q("ellipse")):
            attrs = " ".join(
                f'{k}="{v}"' for k, v in e.attrib.items() if k != "fill"
            )
            cut_shapes += f'<ellipse {attrs} fill="#000000"/>'
    mask = (
        '<mask id="cp-cutout" maskUnits="userSpaceOnUse" '
        'x="0" y="0" width="1024" height="1024">'
        '<rect width="1024" height="1024" fill="#FFFFFF"/>'
        f"{cut_shapes}</mask>"
    )
    pets = ""
    for gid in ("cp-dog", "cp-cat"):
        pets += (
            f'<g id="{gid}" fill="var(--cp-orange)">'
            + children_str(groups[gid], tag="path")
            + "</g>"
        )
    heart = (
        '<g id="cp-heart" fill="var(--cp-orange)">'
        + children_str(groups["cp-heart"], tag="path")
        + "</g>"
    )
    return (
        f"<defs>{mask}</defs>"
        # The pets occupy the middle ~60% of the viewBox (bbox x236-852,
        # y310-920); scale the composition up so the no-circle mark reads
        # at small sizes. Fitted: 1.35 about (544, 600) fills ~80% unclipped.
        '<g transform="translate(512 512) scale(1.4) translate(-544 -615)">'
        f'<g mask="url(#cp-cutout)">{pets}</g>'
        f"{heart}</g>"
    )


def build_layer(groups, gid) -> str:
    return ET.tostring(groups[gid], encoding="unicode")


def main() -> None:
    root, badge, groups, varmap = parse_master()

    if len(sys.argv) == 3 and sys.argv[1] == "--stamp":
        Path(sys.argv[2]).write_text(
            one_line(stamp(ET.tostring(root, encoding="unicode"), varmap)) + "\n"
        )
        print(f"stamped master -> {sys.argv[2]}")
        return
    if len(sys.argv) != 1:
        sys.exit("usage: sync_icons_dart.py [--stamp OUT.svg]")

    badge_doc = doc(ET.tostring(badge, encoding="unicode"), varmap, "badge")
    master_text = MASTER.read_text()
    launcher_doc = one_line(stamp(master_text, varmap))
    foreground_doc = doc(build_foreground(badge), varmap, "foreground")
    nocircle_doc = doc(build_nocircle(groups), varmap, "nocircle")
    layers = {gid: doc(build_layer(groups, gid), varmap, f"layer:{gid}") for gid in GROUP_IDS}

    # Generated files (stamped, render-safe).
    (ICON_DIR / "app_icon_foreground.svg").write_text(foreground_doc + "\n")
    (ICON_DIR / "app_icon_nocircle.svg").write_text(nocircle_doc + "\n")
    print("wrote tool/icon/app_icon_foreground.svg")
    print("wrote tool/icon/app_icon_nocircle.svg")

    dart_consts = {
        "badgeArtwork": badge_doc,
        "launcherArtwork": launcher_doc,
        "launcherForegroundArtwork": foreground_doc,
        "badgeNoCircleArtwork": nocircle_doc,
        "splashLayerCircle": layers["cp-circle"],
        "splashLayerDog": layers["cp-dog"],
        "splashLayerCat": layers["cp-cat"],
        "splashLayerHeart": layers["cp-heart"],
    }
    docs = {
        "badgeArtwork": "The badge alone (orange disc + dog + cat + heart), no tile.",
        "launcherArtwork": "Cream tile + badge. Full master document.",
        "launcherForegroundArtwork": "Transparent + badge at 60% (adaptive-icon foreground).",
        "badgeNoCircleArtwork": "Silhouettes only: orange pets, heart + eyes knocked out. For light surfaces.",
        "splashLayerCircle": "Splash-morph layer.",
        "splashLayerDog": "Splash-morph layer.",
        "splashLayerCat": "Splash-morph layer.",
        "splashLayerHeart": "Splash-morph layer.",
    }
    block = [
        "  // BEGIN GENERATED ICON ARTWORK — do not hand-edit.",
        "  // Generated by tool/sync_icons_dart.py from tool/icon/app_icon.svg",
        "  // (CarePaws mark v5, refined variant A). Colors are stamped from the",
        "  // SVG :root variables, which mirror lib/design/tokens.dart.",
        "",
    ]
    for name, svg in dart_consts.items():
        block.append(f"  /// {docs[name]}")
        block.append(f"  static const {name} =")
        block.append(f"      '{svg}';")
        block.append("")
    block.append("  // END GENERATED ICON ARTWORK")
    block_text = "\n".join(block)

    dart = DART_FILE.read_text()
    pattern = re.compile(
        r"  // BEGIN GENERATED ICON ARTWORK.*?  // END GENERATED ICON ARTWORK",
        re.S,
    )
    if not pattern.search(dart):
        sys.exit("sync_icons_dart: marker block not found in lib/design/icons.dart")
    DART_FILE.write_text(pattern.sub(block_text, dart))
    print("updated lib/design/icons.dart")


if __name__ == "__main__":
    main()
